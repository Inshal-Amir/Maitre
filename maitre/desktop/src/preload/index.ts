import { contextBridge, ipcRenderer, webUtils } from 'electron';
import type { AgentEvent, MaitreApi } from '../shared/types';

const api: MaitreApi = {
  listConversations: () => ipcRenderer.invoke('conversations:list'),
  getConversation: (id) => ipcRenderer.invoke('conversations:get', id),
  createConversation: (mode, cwd) => ipcRenderer.invoke('conversations:create', mode, cwd),
  deleteConversation: (id) => ipcRenderer.invoke('conversations:delete', id),
  renameConversation: (id, title) => ipcRenderer.invoke('conversations:rename', id, title),
  setWorkDir: (id) => ipcRenderer.invoke('conversations:set-cwd', id),
  setConversationFolder: (id, dir) => ipcRenderer.invoke('conversations:set-folder', id, dir),
  send: (id, text, attachmentIds) => ipcRenderer.invoke('agent:send', id, text, attachmentIds ?? []),
  attachFiles: (paths) => ipcRenderer.invoke('attachments:add', paths ?? []),
  attachImage: (name, dataUrl) => ipcRenderer.invoke('attachments:add-image', name, dataUrl),
  pathForFile: (file) => webUtils.getPathForFile(file),
  stop: (id) => ipcRenderer.invoke('agent:stop', id),
  retry: (id) => ipcRenderer.invoke('agent:retry', id),
  decide: (id, decision) => ipcRenderer.invoke('agent:decide', id, decision),
  answer: (id, answers) => ipcRenderer.invoke('agent:answer', id, answers),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  saveSettings: (patch) => ipcRenderer.invoke('settings:save', patch),
  chooseDirectory: (current) => ipcRenderer.invoke('dialog:directory', current),
  modelStatus: () => ipcRenderer.invoke('model:status'),
  connectAccount: (email, password, create) => ipcRenderer.invoke('account:connect', email, password, create),
  accountStatus: () => ipcRenderer.invoke('account:status'),
  signOut: () => ipcRenderer.invoke('account:sign-out'),
  listConnectors: () => ipcRenderer.invoke('connectors:list'),
  connectGoogle: (services) => ipcRenderer.invoke('connectors:google-connect', services),
  disconnectGoogle: () => ipcRenderer.invoke('connectors:google-disconnect'),
  saveMcpServer: (config) => ipcRenderer.invoke('connectors:save', config),
  removeMcpServer: (id) => ipcRenderer.invoke('connectors:remove', id),
  reconnectMcpServer: (id) => ipcRenderer.invoke('connectors:reconnect', id),
  importMcpJson: (json) => ipcRenderer.invoke('connectors:import-json', json),
  checkCommands: (commands) => ipcRenderer.invoke('connectors:check-commands', commands),
  setServerVars: (id, values) => ipcRenderer.invoke('connectors:set-vars', id, values),
  listSkills: (cwd) => ipcRenderer.invoke('skills:list', cwd),
  getSkill: (id) => ipcRenderer.invoke('skills:get', id),
  saveSkill: (draft, replaceId) => ipcRenderer.invoke('skills:save', draft, replaceId),
  deleteSkill: (id) => ipcRenderer.invoke('skills:delete', id),
  setSkillEnabled: (id, enabled) => ipcRenderer.invoke('skills:set-enabled', id, enabled),
  importSkillFolder: (dir) => ipcRenderer.invoke('skills:import-folder', dir),
  listTools: () => ipcRenderer.invoke('tools:list'),
  setToolEnabled: (name, enabled) => ipcRenderer.invoke('tools:set-enabled', name, enabled),
  listPlugins: () => ipcRenderer.invoke('plugins:list'),
  inspectSource: (source) => ipcRenderer.invoke('plugins:inspect', source),
  inspectMarketplacePlugin: (marketplaceId, name) => ipcRenderer.invoke('plugins:inspect-marketplace', marketplaceId, name),
  confirmPlugin: (stagingId) => ipcRenderer.invoke('plugins:confirm', stagingId),
  cancelPlugin: (stagingId) => ipcRenderer.invoke('plugins:cancel', stagingId),
  setPluginEnabled: (id, enabled) => ipcRenderer.invoke('plugins:set-enabled', id, enabled),
  removePlugin: (id) => ipcRenderer.invoke('plugins:remove', id),
  updatePlugin: (id) => ipcRenderer.invoke('plugins:update', id),
  listMarketplaces: () => ipcRenderer.invoke('marketplaces:list'),
  refreshMarketplace: (id) => ipcRenderer.invoke('marketplaces:refresh', id),
  removeMarketplace: (id) => ipcRenderer.invoke('marketplaces:remove', id),
  listMemories: () => ipcRenderer.invoke('memories:list'),
  deleteMemory: (id) => ipcRenderer.invoke('memories:delete', id),
  clearMemories: () => ipcRenderer.invoke('memories:clear'),
  listProcesses: () => ipcRenderer.invoke('processes:list'),
  stopProcess: (id) => ipcRenderer.invoke('processes:stop', id),
  openExternal: (url) => ipcRenderer.invoke('shell:open-external', url),
  revealPath: (target) => ipcRenderer.invoke('shell:reveal', target),
  openDocument: (target) => ipcRenderer.invoke('shell:open-document', target),
  platform: process.platform,
  onEvent(listener) {
    const wrapped = (_event: Electron.IpcRendererEvent, payload: AgentEvent): void => listener(payload);
    ipcRenderer.on('maitre:event', wrapped);
    return () => ipcRenderer.removeListener('maitre:event', wrapped);
  },
};

contextBridge.exposeInMainWorld('maitre', api);
